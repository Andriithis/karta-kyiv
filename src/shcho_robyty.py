def dzherelo(k):
    if not k: return '<span class="muted">досвід, оцінок немає</span>'
    n, u = DZH[k]
    return f'<a href="{u}" target="_blank" rel="noopener">{esc(n)}</a>'


SYLA = {'сильно': 'sy-s', 'помірно': 'sy-p', 'слабко': 'sy-l', 'не працює': 'sy-n'}


def pryklady(mekh, an):
    zz = sorted([z for z in an if z.get('mekhanizm') in mekh], key=lambda z: -z.get('n_stsenariju', 0))[:2]
    return ''.join(f'<li><a href="index.html#m={z["lat"]:.5f},{z["lon"]:.5f}">{esc(z["adresy"][0])}</a> — '
                   f'{esc(z["stsenarij"])} <span class="muted">({z.get("n_stsenariju", 0)} з {z.get("n_usikh", 0)})</span></li>'
                   for z in zz)


