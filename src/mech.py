def is_proactive(code):
    """код категорії -> чи подію виявила сама поліція"""
    g = simgroup(code) or ''
    return g in PROACTIVE or simtheme(g) in PROACTIVE_THEMES

# ГП_хуліг ділиться за фабулою (Р2): дії, спрямовані на поліцейських, —
# протокол склала сама поліція на себе ж, тож подія проактивна. На тесті
# 22.09 це ≈15% дрібного хуліганства.
import re as _re
HULIG_NA_POLICIYU = _re.compile(r'в\s+бік\s+працівник\w*\s+поліці|поліцейськ|патрульн', _re.I)

def is_proactive_event(code, fab=''):
    """як is_proactive, але з поділом хуліганства за фабулою"""
    if is_proactive(code): return True
    return simgroup(code) == 'ГП_хуліг' and bool(HULIG_NA_POLICIYU.search(fab or ''))


