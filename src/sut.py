# -*- coding: utf-8 -*-
"""Суть фабули — окремий крок поверх фабули з проходу (step1c_teksty).

Фабула з проходу — це логічний уривок рішення: у ньому й досі вступ про
надходження протоколу, формули умислу, судимість, службові маркери. Слухачеві
на карті треба інше: хто, коли, де, що зробив і що з цього вийшло. sut()
вирізає юридичні домішки й підрізає до ~500 знаків по межі речення; повна
фабула лишається в даних і в самому рішенні («відкрити рішення»).

Правила — лише вирізання: жодного слова, якого не було у фабулі, sut() не
дописує. Тому помилка правила може лише залишити зайве чи вирізати зворот,
але не вигадати факт.
"""
import re
import step1c_teksty as TK

SUT_CAP = 500

_I = re.I

# ---- ВСТУП ПРО НАДХОДЖЕННЯ ----
# Ціле речення: «До Солом'янського районного суду м. Києва надійшли матеріали
# (надійшов протокол) …» — події в ньому немає.
INTRO_SENT = re.compile(r'^\s*(?:Постановою\s+[^.]{0,120}?суду|До\s+[^.]{0,120}?суд\w*[^.]{0,80}?надійш\w+|'
                        r'На\s+розгляд\s+[^.]{0,80}?надійш\w+)', _I)
# Префікс речення: після нього — вже сама подія.
_PROT = (r'(?:змісту\s+|тексту\s+)?(?:даного\s+|вказаного\s+|зазначеного\s+|цього\s+)?протокол\w*'
         r'(?:\s+про\s+адміністративн\w+\s+правопорушен\w+)?'
         r'(?:\s+серії\s+[А-ЯІЇЄҐA-Z]{1,4})?(?:\s*№\s*[\w/-]+)?'
         r'(?:\s+від\s+\d{1,2}[./]\d{1,2}[./]\d{2,4}\s*(?:року|р\.)?)?')
INTRO_PREFIX = re.compile(
    r'^\s*(?:(?:Відповідно\s+до|Згідно\s+(?:з|із)?|Як\s+вбачається\s+(?:з|із))\s+' + _PROT + r'\s*,?\s*(?:складеного\s+[^,]{0,120},\s*)?|'
    r'(?:Відповідно\s+до|Згідно\s+(?:з|із)?)\s+(?:висунутого\s+|пред.явленого\s+)?обвинувачення'
    r'(?:\s+органом\s+досудового\s+розслідування)?\s*,?\s*|'
    r'(?:Органом\s+)?[Дд]осудов\w+\s+розслідуванням\s+встановлено\s*,?\s*(?:що\s+)?|'
    r'(?:Судом|Суддею)\s+(?:встановлено|визнано\s+доведеним)\s*,?\s*(?:що\s+)?|'
    r'Обвинувачен\w+\s+(?=ОСОБА_))', _I)
# «…серії ВАД № 284016 16.09.2025 року за адресою» — дата протоколу стоїть
# без «від», і якщо вона ж — дата події, лишаємо її: різати тут не можна.

# ---- СУДИМІСТЬ, ЩО ПІДВОДИТЬ ДО ПОДІЇ ----
PRIOR = re.compile(r',?\s*будучи\s+(?:особою\s*,?\s*(?:яку|яка)\s+)?(?:раніше\s+)?'
                   r'(?:протягом\s+року\s+)?(?:судим|засуджен|притягнут|притяга)\w*[^,]{0,200}?'
                   r'(?:,\s*[^,.]{0,80}?(?:КК|КУпАП)(?:\s+України)?)?\s*,', _I)
# Речення-вступ: «…вчинив кримінальне правопорушення за наступних обставин.»
PRIOR_SENT = re.compile(r'за\s+(?:наступних|таких)\s+обставин\s*[.:]?\s*$', _I)

# ---- ФОРМУЛИ УМИСЛУ ----
# Умисел рідко вміщається до першої коми: «умисел, спрямований на незаконне
# придбання …, обіг якого обмежено - метадону, для власного вживання, без
# мети збуту,». Тому після «умисел … на …» з'їдаємо й наступні частини, що
# лише уточнюють предмет умислу, — і зупиняємось на першій, що несе подію
# (дату, місце, учасника).
_CONT = (r'(?:для\s+|без\s+мети|обіг\s+як|в\s+умовах\s+воєнного|з\s+метою|у\s+великих|особливо\s+небезпечн|'
         r'психотропн|наркотичн|а\s+саме\s+[а-яіїєґ]|тобто\s+[а-яіїєґ]|що\s+належ|як\w+\s+належ|чужого\s+майна|'
         r'повторно|таємно|відкрито|з\s+корисливих|в\s+особливо|у\s+значних)')
_OBJ = r'(?:\s*,?\s*(?:спрямован\w*|направлен\w*)?\s*на\s+[^,.]*)?(?:\s*,\s*' + _CONT + r'[^,.]*)*'
_WHO = r'(?:нього|неї|них|ОСОБА_\d+|останнього|останньої|обвинувачен\w+)'
INTENT = [
    re.compile(r'(?:,\s*)?(?:(?:де|після\s+чого|під\s+час\s+якого|тоді|в\s+той\s+момент|у\s+цей\s+час|в\s+цей\s+час|надалі)\s*,?\s*)?'
               r'(?:(?:у|в)\s+(?:[\w\'-]+\s+)?' + _WHO + r'\s*,?\s+)?(?:[\w\'-]+\s+){0,2}?винн?ик\w*\s+(?:[\w\'-]+\s+){0,3}?умисел' + _OBJ + r'\s*[,]?\s*', _I),
    re.compile(r'(?:,\s*)?(?:реалізуючи|реалізовуючи|маючи|продовжуючи\s+реалізацію|з\s+метою\s+реалізації)\s+(?:на\s+меті\s+)?'
               r'(?:свій\s+|свого\s+|цей\s+|спільний\s+)?(?:[\w\'-]+\s+){0,3}?(?:умисел|умислу|намір)' + _OBJ + r'\s*,\s*', _I),
    re.compile(r'(?:,\s*)?усвідомлюючи\s+суспільно[\s-]*небезпечн[^.]{0,300}?бажаючи\s+(?:їх|її|його)\s+настання\s*,?\s*', _I),
    # решта форм «усвідомлюючи …, передбачаючи …, бажаючи …» — до першої
    # частини, що не продовжує формулу
    re.compile(r'(?:,\s*)?усвідомлюючи\b\s*,?\s*(?:що\s+)?[^,.]{0,200}(?:,\s*(?:передбачаючи|розуміючи|бажаючи|та\s+бажаючи|і\s+бажаючи|'
               r'свідомо|вважаючи|допускаючи)[^,.]{0,200})*\s*,?\s*', _I),
    re.compile(r'(?:,\s*)?(?:тобто\s+)?діючи\s+з\s+прямим\s+умислом\s*,?\s*', _I),
    re.compile(r'(?:,\s*)?діючи\s+умисно\s*,?\s*', _I),
    re.compile(r'(?:,\s*)?діючи\s+з\s+корисливих\s+мотивів(?:\s*,?\s*(?:та|і)\s+бажаючи\s+[^,.]{0,100})?\s*,?\s*', _I),
    re.compile(r'з\s+метою\s+особистого\s+(?:незаконного\s+)?збагачення\s*,?\s*', _I),
]
# Хвіст про указ: «в умовах воєнного стану, який введено з 05 години 30
# хвилин 24.02.2022 Указом Президента … строком на 90 діб відповідно».
# Сам «в умовах воєнного стану» — кваліфікуюча ознака, теж не суть.
MARTIAL = re.compile(r',?\s*(?:тобто\s+)?(?:(?:в|у)\s+умовах|(?:в|у)\s+період\s+дії|під\s+час\s+дії|в\s+час\s+дії)\s+'
                     r'(?:дії\s+)?(?:правового\s+режиму\s+)?воєнного\s+стану'
                     r'(?:\s*,?\s*(?:(?:який|що)\s+(?:введен|запроваджен|діє)\w*|введен\w*|запроваджен\w*|згідно|відповідно\s+до)'
                     r'.{0,400}(?:відповідно|діб|продовжен\w*|продовжувався|«[^»]{0,200}»|№\s*[\d/-]+(?:-[IVXІ]+)?)(?=[\s,.]))?', _I)
# «…відносно ОСОБА_1 було складено протокол про вчинення ним 04.10.2025 р.
# адміністративного правопорушення, в тому, що …» — до «що» це рамка.
PROT_SENT = re.compile(r'^[^.]{0,250}?складено\s+протокол\w*[^.]{0,250}?'
                       r'(?:за\s+те|про\s+те|в\s+тому|в\s+тім|у\s+тому|згідно\s+з\s+яким\w*)\s*,?\s*(?:що\s+)?', _I)
LEAD_SO = re.compile(r'^(?:Так|Отже|Зокрема)\s*,\s*', _I)
LOOSE_END = re.compile(r'[,\s]*(?:після\s+чого|під\s+час\s+якого|в\s+той\s+момент|у\s+цей\s+час|де|тоді|надалі|а)\s*$', _I)

# ---- СЛУЖБОВІ МАРКЕРИ ----
# ІНФОРМАЦІЯ_N у лапках — знеособлена назва каналу чи закладу, її лишаємо:
# «у телеграм-каналі «ІНФОРМАЦІЯ_2»» без неї втрачає сенс. Прибираємо лише
# ту, що стоїть при учасникові (дата народження).
MARKERS = [
    (re.compile(r'(ОСОБА_\d+)\s*,?\s*ІНФОРМАЦІЯ_\d+\s*(?=[,.;)]|\s+(?:та|і|й|було|був|була)\b|$)'), r'\1'),
    (re.compile(r'\s*,\s*ІНФОРМАЦІЯ_\d+\s*(?=[,.;)]|$)'), ''),             # «ОСОБА_1, ІНФОРМАЦІЯ_1,»
    (re.compile(r',?\s*(?:з\s+)?(?:державн\w+\s+номерн\w+\s+знак\w*|номерн\w+\s+знак\w*|реєстраційн\w+\s+номер\w*|'
                r'ідентифікаційн\w+\s+код\w*(?:\s+фізичної\s+особи)?|д\.?\s?н\.?\s?з\.?|д/н|н\.\s?з\.)\s*'
                r'(?:№\s*)?(?:[«"]?НОМЕР_\d+[»"]?|(?=\s*$))', _I), ''),
    (re.compile(r'\s*(?:№\s*)?НОМЕР_\d+'), ''),
    (re.compile(r'\.\.(?=\s)'), '.'),                                        # «просп.. Берестейський»
]

# ---- ХВІСТ КВАЛІФІКАЦІЇ ----
# «…, за що відповідальність передбачена, ст. 173 КУпАП» — tidy_end такого не
# бере (кома всередині), а на екрані суті він зайвий.
QUAL_TAIL = re.compile(r'[,\s]*(?:за\s+що|чим\s+(?:самим\s+)?(?:вчинив|скоїв)|тим\s+самим\s+(?:вчинив|скоїв)|'
                       r'своїми\s+(?:умисними\s+)?діями\s+(?:вчинив|скоїв))[^.]{0,200}?'
                       r'(?:ст\.|статт\w*)\s*[\d\-]+[^.]{0,60}\.?\s*$', _I)

# ---- ДУБЛІ ----
SAME_DAY = re.compile(r'(?:^|(?<=[\s,]))(?:(?:у|в)\s+)?(?:той|цей)\s+(?:же|ж)\s+(?:день|час)\s*,?\s*|'
                      r'(?:^|(?<=[\s,]))(?:того|цього)\s+ж(?:е)?\s+дня\s*,?\s*', _I)
SAME_PLACE = re.compile(r',?\s*(?:за|по)\s+(?:вище)?(?:вказан|зазначен)\w+\s+адрес\w*\s*,?', _I)
DATE = re.compile(r'(?:,?\s*(?:а\s+саме\s+)?)(\d{1,2}[./]\d{1,2}[./]20\d{2}|\d{1,2}\s+(?:січня|лютого|березня|квітня|'
                  r'травня|червня|липня|серпня|вересня|жовтня|листопада|грудня)\s+20\d{2})'
                  r'(?:\s*(?:року|р\.))?\s*,?', _I)


def _norm_date(s):
    return re.sub(r'\D+', '.', s.strip()).strip('.')


def _tidy(s):
    s = re.sub(r'\s+([,.;:])', r'\1', s)
    s = re.sub(r',\s*,', ',', s)
    s = re.sub(r'\s{2,}', ' ', s).strip(' ,;')
    return s


def _cap(s):
    return s[:1].upper() + s[1:] if s else s


def sut(fab, cap=SUT_CAP):
    """Суть фабули: хто, коли, де, що зробив, наслідок."""
    if not fab:
        return fab
    t = TK.tidy_end(fab)
    for rx, rep in MARKERS:
        t = rx.sub(rep, t)
    out, seen_dates = [], set()
    for s in TK._sentences(t):
        s = s.strip()
        if not s or INTRO_SENT.search(s):
            continue
        if PRIOR_SENT.search(s) and not TK.is_event_sentence(s):
            continue
        if TK.MARTIAL.search(s) and not TK.ACTOR.search(s):
            continue                     # абзац про указ без учасника
        s = INTRO_PREFIX.sub('', s, count=1)
        s = PROT_SENT.sub('', s, count=1)
        s = LEAD_SO.sub('', s)
        s = PRIOR.sub(',', s)
        s = MARTIAL.sub('', s)
        s0 = s
        for rx in INTENT:
            s = rx.sub(' ', s)
        s = LOOSE_END.sub('', s.rstrip(' .'))
        # від речення про умисел лишився уривок без учасника («У невстановлений
        # час, але не пізніше 17.02.2023,») — події в ньому немає
        if s != s0 and not TK.ACTOR.search(s) and len(s) < 150:
            continue
        if not out:
            # «Надалі, …» першим реченням — зв'язка з вирізаним реченням
            s = re.sub(r'^(?:Надалі|Після\s+цього|Після\s+чого|В\s+подальшому|У\s+подальшому|Потім)\s*,?\s*', '', s, flags=_I)
        if out:
            # повтор дня й місця в сусідньому реченні: лишаємо перше
            s = SAME_DAY.sub('', s)
            s = SAME_PLACE.sub(',', s)
            def _drop(m):
                return ' ' if _norm_date(m.group(1)) in seen_dates else m.group(0)
            s = DATE.sub(_drop, s)
        for m in DATE.finditer(s):
            seen_dates.add(_norm_date(m.group(1)))
        s = _cap(_tidy(s))
        if len(s) > 3:
            out.append(s)
    # Не та частина рішення («Постановою суду … повернуто», «Основною
    # конституційною засадою…»): жодного учасника — суті немає, панель
    # покаже рішення без опису, як і для шкідливої фабули.
    if not any(TK.ACTOR.search(x) or TK.is_event_sentence(x) for x in out):
        return ''
    t = ' '.join(x if x.endswith(('.', '!', '?', '…')) else x + '.' for x in out)
    t = QUAL_TAIL.sub('', t).strip()
    t = TK._cut(t, cap).rstrip(' ,;:')
    return t
