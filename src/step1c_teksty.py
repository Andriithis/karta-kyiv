MIN_BEFORE_END = 60        # маркер кінця на самому початку — не кінець, а зворот
# Після маркера кінця від останнього речення часто лишається уривок: «У
# результаті протиправних дій ОСОБА_5». Коротший за це — відкидаємо до межі
# речення: обірване речення гірше, ніж на одне речення коротша фабула.
STUB = 90

MONTHS = {m: i + 1 for i, m in enumerate(
    'січня лютого березня квітня травня червня липня серпня вересня жовтня листопада грудня'.split())}
DATE_NUM = re.compile(r'\b(\d{1,2})[.\s/-](\d{1,2})[.\s/-](20\d{2})')
