# -*- coding: utf-8 -*-
"""Дрібні текстові помічники, спільні для двигуна, карти й документів.

Заведено 10 вересня. Привід — «у 5.47 рази краще за випадковий відбір»:
крапка замість коми й жорстке «рази» незалежно від числа. Кратність у нас
здебільшого дробова, а для дробових українською відмінок завжди однаковий
(«раза»); для цілих він залежить від останньої цифри.

Окремий файл, а не рядок у labels.py, навмисно: labels — це словники кодів
статей, і дописувати туди форматування тексту означало б міняти файл, який
має лишатися стабільним.
"""


def raziv(n):
    """Кратність із правильним відмінком і комою.

    1.8 -> '1,8 раза' · 2 -> '2 рази' · 5 -> '5 разів' · 21 -> '21 раз'
    """
    v = round(float(n), 1)
    t = f'{v:g}'.replace('.', ',')
    if v != int(v):
        return t + ' раза'
    a, b = int(v) % 10, int(v) % 100
    if a == 1 and b != 11:
        return t + ' раз'
    if 2 <= a <= 4 and not 12 <= b <= 14:
        return t + ' рази'
    return t + ' разів'
