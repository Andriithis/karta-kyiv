def _pershe(slovnyk, t):
    """Перше значення словника за пріоритетом, яке є в тексті; немає — None."""
    return next((k for k, rx in slovnyk if rx.search(t)), None)


def tsil(theme, sim, fab):
    """{поле: значення} для виду події; порожній словник — цілі в тексті немає.
    theme — код виду (labels.ORDER), sim — механізм (для торгівлі й хуліганства)."""
    t = fab or ''
    if not t: return {}
    out = {}
    if theme == 'МАЙ':
        if KRADIZHKA.search(t):
            b = _pershe(BERUT, TARA.sub(' ', t))
            if b: out['berut'] = b
        m = MEREZHA.search(t)
        if m: out['u_koho'], out['merezha'] = 'магазин', m.group(1)
        elif MAGAZYN_SYLNO.search(t): out['u_koho'] = 'магазин'
        elif LIUDYNA.search(t): out['u_koho'] = 'людина'
        elif MAGAZYN.search(t): out['u_koho'] = 'магазин'
    elif theme == 'ДТП':
        z = _pershe(ZITKN, t)
        if z: out['zitknennia'] = z
    elif theme == 'ГП' and 'хуліг' in (sim or '') or theme == 'ГП' and re.search(r'хуліган', t, re.I):
        n = _pershe(NA_KOHO, t)
        if n: out['na_koho'] = n
    elif theme == 'НАР':
        r = _pershe(RECHOVYNA, t)
        s = _pershe(SPOSIB, t)
        if r: out['rechovyna'] = r
        if s: out['sposib'] = s
    elif theme == 'АЛК' and (sim or '').startswith('АЛК_торгівля'):
        p = _pershe(PRODAIUT, t)
        if p: out['shcho_prodaiut'] = p
    return out
