# інакше вона відкривалася б абзацом про надходження обвинувального акта.
SECTION = re.compile(r'(?:обставини\s*,?\s*(?:що\s+|які\s+)?встановлені\s+судом|'
                     r'встановлені\s+судом\s+обставини|формулювання\s+обвинувачення'
                     r'(?:\s*,\s*визнаного\s+судом\s+доведеним)?)\s*[:.]?', re.I)
SECTION_WINDOW = 6000
# Сама назва розділу довга й сама по собі не фабула: «Формулювання
# обвинувачення, яке визнано судом доведеним (із зазначенням місця, часу,
# способу вчинення … мотивів кримінального правопорушення)». Її хвіст
# пропускаємо до крапки чи двокрапки після «доведеним» / «правопорушення».
SECTION_TAIL = re.compile(r'\s*[,(]?[^.:]{0,400}(?:доведеним|недоведеним|правопорушення|проступку)'
                          r'\s*\)?\s*[.:]?', re.I)
# Вирок, від якого проголошено лише вступну й резолютивну частини: опису
# події в ньому немає зовсім, повний текст виходить окремим документом.
SHORT_VERDICT = re.compile(r'(?:вступн\w*\s+(?:та|і)\s+резолютивн\w*\s+частин|'
                           r'проголошенням\s+його\s+резолютивн)', re.I)
# Речення на початку, які подією не є: надходження акта, реєстр, клопотання,
# і абзац про введення воєнного стану — з нього «датою події» ставала
# 24.02.2022. Відкидаємо їх, доки не почнеться опис (не далі восьми речень).
LEAD_JUNK = re.compile(r'надійш|обвинувальн\w*\s+акт|ЄРДР|Єдиного\s+реєстру|клопотан|'
                       r'в\s+порядку\s+ст|спрощен\w*\s+провадж|прокуратур|роз.?яснено|'
                       r'Указ\w*\s+Президента|воєнн\w+\s+стан|Закон\w*\s+України|'
                       # вступ до фабули: «вчинив проступок за таких обставин»,
                       # «встановлено наступні обставини, які не оспорюються»
                       r'за\s+(?:таких|наступних)\s+(?:\S+\s+){0,4}?обставин|'
                       r'обставин\w*,?\s+які\s+не\s+оспорю|встановлено\s+наступн\w+\s+обставин', re.I)
# Опора: речення, де є і дата, і час, — це опис події, навіть якщо в ньому
# трапився реєстр чи воєнний стан. Таке речення ніколи не відкидаємо.
_D = r'(?:\d{1,2}[.\s/-]\d{1,2}[.\s/-]20\d{2}|\d{1,2}\s+(?:січня|лютого|березня|квітня|травня|червня|' \
     r'липня|серпня|вересня|жовтня|листопада|грудня)\s+20\d{2})'
_T = r'(?:(?:\bо|\bоб|близько|приблизно|орієнтовно)\s*\d{1,2}\s*(?:год|:|\.\d\d)|\bз\s*\d{1,2}[.:]\d{2})'
HAS_DATE, HAS_TIME = re.compile(_D, re.I), re.compile(_T, re.I)


# Абзац про введення воєнного стану теж має дату й час («з 05 год. 30 хв.
# 24 лютого 2022 року»), але подією не є, поки в ньому немає учасника.
MARTIAL = re.compile(r'Указ\w*|воєнн\w+\s+стан\w*|Закон\w*\s+України', re.I)
ACTOR = re.compile(r'ОСОБА_\d|Особа\s+1')


# Дата й час засідання — теж не подія: «у судове засідання, призначене на
# 30.09.2025 о 10:00, не з'явилась». З таких постанов (про привід, про
# об'єднання справ) опису правопорушення не буває.
COURT_PROC = re.compile(r'судов\w+\s+засідан|призначен\w+\s+на\s+\d|не\s+з.?явил|привод|привід|'
                        r'об.?єдна\w+\s+(?:справ|провадж)|провадженні\s+суду\s+перебува|'
                        r'звернув\w*\s+до\s+суду|речов\w+\s+доказ|справ\w*\s+.{0,60}розглянут', re.I)


# Адреса поруч із датою — теж ознака опису, коли часу в протоколі не вказано.
ADDR_CUE = re.compile(r'за\s+адрес\w*|по\s+(?:вул|просп|бульв|пров|пл)\w*\.?|біля\s+буд|АДРЕСА_\d', re.I)


def is_event_sentence(s):
    d = HAS_DATE.search(s)
    if not d or (MARTIAL.search(s) and not ACTOR.search(s)):
        return False
    # процедура вбиває речення, лише коли стоїть ПЕРЕД датою: «у судове
    # засідання, призначене на 30.09.2025 о 10:00». Після дати події вона —
    # уже продовження довгого речення, а не його суть.
    p = COURT_PROC.search(s)
    if p and p.start() < d.start():
        return False
    return bool(HAS_TIME.search(s) or ADDR_CUE.search(s, d.start()))


# «До суду надійшов протокол …. Відповідно до вказаного протоколу, ОСОБА_1
# 22 серпня …» бувають одним реченням — опис починається з другої половини.
INNER_START = re.compile(r'(?:відповідно\s+до|згідно\s+(?:з\s+|із\s+)?|як\s+вбачається\s+з)\s*'
                         r'(?:вказаного\s+|даного\s+)?протокол', re.I)

