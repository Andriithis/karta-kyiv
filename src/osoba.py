# -*- coding: utf-8 -*-
"""Поля особи й цілі з повного тексту рішення (36.41; ZAVDANNYA-40 4.1–4.2,
ZAVDANNYA-41 2.3). Рахує нічний прохід (step1c_teksty.rozbir), поки текст у
пам'яті раннера; у data/teksty іде лише компактний JSON кодів — повний текст
нікуди не йде (36.25, S-Б.4), заглушок «ОСОБА_» у полях немає (S-Б.5).

Частини рішення: вступ (до «встановив»), мотивувальна (до «ухвалив/постановив»)
і резолютивна. Особу описують вступ і мотивувальна («раніше судимого…»,
«не працює», «на обліку в лікаря-нарколога не перебуває»), призначене — у
резолютивній. Поле береться лише з прямо написаного; немає — поля немає
(картка пише «— у рішенні не вказано»). Потерпілого — лише прямо названого.
"""
import re

_W = r'[\w\'’ʼ-]*'

def chastyny(text):
    """(вступ, мотивувальна, резолютивна)"""
    t = re.sub(r'\s+', ' ', text or '')
    m1 = re.search(r'\bв\s*с\s*т\s*а\s*н\s*о\s*в\s*и\s*(?:в|л)\b', t, re.I)
    a = m1.start() if m1 else min(len(t), 3000)
    m2 = re.search(r'П\s*О\s*С\s*Т\s*А\s*Н\s*О\s*В\s*И\s*(?:В|Л)|У\s*Х\s*В\s*А\s*Л\s*И\s*(?:В|Л)|В\s*И\s*Р\s*І\s*Ш\s*И\s*(?:В|Л)', t[a + 20:])
    b = a + 20 + m2.start() if m2 else len(t)
    return t[:a], t[a:b], t[b:]


# (поле, вираз, значення) — перше, що знайшлось у вступі чи мотивувальній
NE_SUDYMYI = re.compile(r'(?:раніше\s+)?не\s*судим|судимост\w*\s+не\s+ма|не\s+має\s+судимост|вважа\w+\s+таким,?\s+що\s+не\s+ма\w*\s+судимост', re.I)
SUDYMYI = re.compile(r'раніше\s+судим\w*|(?<!не )судим\w*\s*(?::|за\s+вироком|вироком)|має\s+(?:не\s*зняту\s+і\s+не\s*погашену\s+)?судимість', re.I)
ROBOTA = [('ні', re.compile(r'(?:офіційно\s+)?не\s+працю\w+|не\s+працевлаштован\w*|без\s+(?:постійного\s+)?(?:місця\s+)?(?:роботи|заняття)|тимчасово\s+не\s+працю', re.I)),
          ('навчається', re.compile(r'\b(?:студент\w*|учн\w+|навча\w+ся)\b', re.I)),
          ('так', re.compile(r'\bпрацю(?:є|ючого|юча|ючої|ючий)\b|працевлаштован\w*|\bФОП\b|фізичн\w+ особ\w+.?підприєм', re.I)),
          ('пенсіонер', re.compile(r'пенсіонер\w*', re.I))]
# «не в шлюбі» — першим: «не одруженого» містить «одружен» (перевірка 01.11)
SIMJA = [('не в шлюбі', re.compile(r'\b(?:неодружен\w*|не\s*одружен\w*|н\s+одружен\w*|не\s*заміжн\w*|незаміжн\w*|розлучен\w*|'
                                    r'(?:у|в)\s+(?:зареєстрованому\s+)?шлюбі\s+не\s+перебува\w*|не\s+перебува\w+\s+у\s+(?:зареєстрованому\s+)?шлюбі|вдов\w+)', re.I)),
         ('у шлюбі', re.compile(r'\b(?:одружен\w*|заміжн\w*|перебува\w+ у (?:зареєстрованому )?шлюбі)\b', re.I))]
UTRYMANTSI = re.compile(r'(?:має\s+)?на\s+утриманні\s+(?:має\s+)?(?:(\w+)\s+)?(неповнолітн\w+|малолітн\w+|дит\w+|син\w*|доч\w+|непрацездатн\w+)', re.I)
OSVITA = [('вища', re.compile(r'(?:з\s+)?(?:базовою\s+|повною\s+)?вищ\w+\s+освіт', re.I)),
          ('професійна', re.compile(r'професійно.?технічн\w+\s+освіт|середн\w+\s+спеціальн\w+\s+освіт|середн\w+\s+професійн\w+\s+освіт', re.I)),
          ('середня', re.compile(r'(?:повн\w+\s+|базов\w+\s+)?(?:загальн\w+\s+)?середн\w+\s+освіт', re.I))]
OBLIK = lambda likar: re.compile(r'на\s+(?:диспансерн\w+\s+)?обліку\s+(?:у|в)\s+(?:лікар\w*.?)?' + likar + r'\w*\s+(не\s+)?перебува|'
                                 r'(не\s+)?перебува\w+\s+на\s+(?:диспансерн\w+\s+)?обліку\s+(?:у|в)\s+(?:лікар\w*.?)?' + likar, re.I)
NARKOLOG, PSYKHIATR = OBLIK('нарколог'), OBLIK('психіатр')
BEZ_ZHYTLA = re.compile(r'без\s+(?:певного|постійного)\s+місця\s+проживан|не\s+ма\w*\s+(?:постійного\s+|певного\s+)?місця\s+проживан|\bБОМЖ\b|бездомн', re.I)
VIISKOVYI = re.compile(r'\bвійськовослужбов\w+|\bвійськов\w+\s+частин\w+\s+А?\d', re.I)
VPO = re.compile(r'внутрішньо\s+переміщен\w+', re.I)
# назва країни — з великої літери (без re.I: «громадянки до поліції» — не країна;
# перевірка 01.11), і лише у вступі — там описано обвинуваченого
INOZEMETS = re.compile(r'(?i:громадян\w+)\s+(?!України|ОСОБА)(?:Республіки\s+\w+|Російськ\w+\s+Федерації|[А-ЯІЇЄҐ][а-яіїєґ\'’]+(?:\s+[А-ЯІЇЄҐ][а-яіїєґ\'’]+)?)(?=[,\s])|(?i:іноземц\w+|особ\w+\s+без\s+громадянства)')
KHARAKT = re.compile(r'характеризу\w+\s+(?:за\s+місцем\s+(?:проживання|роботи|служби|навчання)\s+)?(позитивно|негативно|задовільно|посередньо)', re.I)
ZVILNENYI = re.compile(r'звільн\w+\s+(?:з|із)\s+(?:місць?\s+позбавлення\s+волі|установ\w*\s+виконання\s+покарань)|звільн\w+\s+(?:умовно.?достроково|по\s+відбутт\w+)', re.I)
# лише «вчинив під час іспитового строку» — «протягом іспитового строку» буває в
# резолютивній частині про нове покарання (перевірка 01.11: 4 хибні з 5)
ISPYTOVYI = re.compile(r'(?:вчини\w*|скої\w*)[^.;]{0,80}(?:під\s+час|протягом|у\s+період|в\s+період)\s+іспитового\s+строку|'
                       r'перебуваючи\s+на\s+іспитовому\s+строку|під\s+час\s+іспитового\s+строку[^.;]{0,40}вчини', re.I)
PRYZNACHENO = [('позбавлення волі', r'позбавлення\s+волі'), ('обмеження волі', r'обмеження\s+волі'),
               ('пробація', r'від\s+відбування\s+покарання\s+з\s+випробуванням|іспитов'), ('громадські роботи', r'громадськ\w+\s+робіт'),
               ('виправні роботи', r'виправн\w+\s+робіт'), ('арешт', r'\bарешт'), ('штраф', r'штраф'),
               ('позбавлення права керувати', r'права\s+керування'), ('звільнено від відповідальності', r'звільнити\s+від\s+(?:кримінальної|адміністративної)\s+відповідальності|закрити')]
PRYZNACHENO = [(k, re.compile(v, re.I)) for k, v in PRYZNACHENO]
# ціль: що повернуто, у кого (лише прямо написане)
POVERNUTO = re.compile(r'(?:повернут\w+|повернено|залишити)\s+(?:потерпіл\w+|власник\w*|законному\s+власник\w*)', re.I)
VARTIST = re.compile(r'(?:вартіст\w*|на\s+суму|розмір\s+(?:майнової\s+)?шкоди)\s*(?:становить\s*|складає\s*|у\s+розмірі\s*|—|-)?\s*(\d[\d\s]{0,9}(?:[,.]\d{1,2})?)\s*(?:грн|гривень)', re.I)


def _pershe(rx, *tt):
    for t in tt:
        m = rx.search(t)
        if m: return m
    return None


def polia(text, dokaz=False):
    """{поле: значення} — лише знайдене; dokaz=True — ще й {поле: вікно навколо
    збігу} для перевірки очима (лише локально, не в дані)"""
    vstup, motyv, rez = chastyny(text)
    out, vik = {}, {}
    def zap(k, v, m, t):
        out[k] = v
        if dokaz and m: vik[k] = t[max(0, m.start() - 90):m.end() + 90]
    m = _pershe(NE_SUDYMYI, vstup, motyv)
    if m: zap('sudymosti', 0, m, vstup if m.string is vstup else motyv)
    else:
        m = _pershe(SUDYMYI, vstup, motyv)
        if m: zap('sudymosti', 1, m, m.string)
    for k, rx in ROBOTA:
        m = _pershe(rx, vstup)
        if m: zap('robota', k, m, m.string); break
    for k, rx in SIMJA:
        m = _pershe(rx, vstup, motyv)
        if m: zap('simja', k, m, m.string); break
    m = _pershe(UTRYMANTSI, vstup, motyv)
    if m: zap('utrymantsi', 1, m, m.string)
    for k, rx in OSVITA:
        m = _pershe(rx, vstup)
        if m: zap('osvita', k, m, m.string); break
    for pole, rx in (('narkolog', NARKOLOG), ('psykhiatr', PSYKHIATR)):
        m = _pershe(rx, motyv, vstup)
        if m: zap(pole, 0 if (m.group(1) or m.group(2)) else 1, m, m.string)
    for pole, rx in (('bez_zhytla', BEZ_ZHYTLA), ('vpo', VPO), ('zvilnenyi', ZVILNENYI), ('ispytovyi', ISPYTOVYI)):
        m = _pershe(rx, vstup, motyv)
        if m: zap(pole, 1, m, m.string)
    # військовий і іноземець — лише вступ: у мотивувальній це часто інші люди
    # («затриманню військовослужбовців країни агресора», «з громадянином Азербайджану»)
    for pole, rx in (('viiskovyi', VIISKOVYI), ('inozemets', INOZEMETS)):
        m = rx.search(vstup)
        if m: zap(pole, 1, m, vstup)
    m = _pershe(KHARAKT, motyv, vstup)
    if m: zap('kharakterystyka', m.group(1).lower(), m, m.string)
    # вид покарання — з першого «призначити … покарання у виді …», а не за
    # порядком списку (139300501: «громадських робіт» — умова заміни штрафу)
    mp = re.search(r'(?:призначити|накласти)[^.;]{0,160}?(?:покарання|стягнення)[^.;]{0,40}?у\s+ви(?:ді|гляді)\s+([^.;]{0,90})', rez, re.I)
    if mp:
        for k, rx in PRYZNACHENO:
            if rx.search(mp.group(1)): zap('pryznacheno', k, mp, rez); break
    if 'pryznacheno' not in out and re.search(r'звільнити\s+від\s+(?:кримінальної|адміністративної)\s+відповідальності|'
                                              r'провадження\s+(?:у\s+справі\s+)?закрити|справу\s+закрити', rez[:1500], re.I):
        out['pryznacheno'] = 'звільнено від відповідальності'
    if out.get('pryznacheno') in ('позбавлення волі', 'обмеження волі') and re.search(
            r'звільнити[^.;]{0,60}від\s+відбування[^.;]{0,120}випробуванн|на\s+підставі\s+ст\.?\s*75', rez, re.I):
        out['pryznacheno'] += ' з випробуванням'
    m = _pershe(POVERNUTO, rez, motyv)
    if m: zap('povernuto', 1, m, m.string)
    m = _pershe(VARTIST, motyv)
    if m:
        try: zap('vartist', int(float(re.sub(r'\s', '', m.group(1)).replace(',', '.'))), m, m.string)
        except ValueError: pass
    return (out, vik) if dokaz else out
