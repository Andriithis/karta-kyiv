TIME = re.compile(r'(?:о|близько|приблизно|орієнтовно|біля)\s*(\d{1,2})\s*(?:год\w*\.?|:)\s*(\d{2})?', re.I)


# Назва розділу стоїть з нового рядка, іноді з номером («2.», «ІІ.»). Ті
# самі слова всередині абзацу мотивів («за обставин, встановлених судом»)
# розділом не є — інакше фабула починалася б із мотивів.
HEADING_BEFORE = re.compile(r'(?:^|[\n\r])[ \t]*(?:[IVXІ]+\.?|\d+(?:\.\d+)*\.?)?[ \t]*$')


def _section(text, bs):
    for m in SECTION.finditer(text, bs, bs + SECTION_WINDOW):
        if HEADING_BEFORE.search(text[max(0, m.start() - 12):m.start()]):
            return m
    return None


# Межі, яких крок 1b не бачить: речення, що починається з дати («… не
# оспорюються. 16.01.2026 року приблизно о 23:00 …»), і речення після суми
# («… 49 448 грн. 80 коп. Будучи …»). Без першої процедура й подія злипалися
# в одне «речення», і відкинути процедуру було неможливо.
# Третя — «ОСОБА_3 . Під час…»: реєстр знеособлює з пробілом перед крапкою.
EXTRA_BOUND = re.compile(r'[а-яіїєґ»)]\.\s+(?=' + _D + r')|\b(?:грн|коп)\.\s+(?=[А-ЯІЇЄҐ][а-яіїєґ])|'
                         r'(?<=\w)\s\.\s+(?=[А-ЯІЇЄҐ])')


def _bounds(t):
    """Межі речень: кроку 1b плюс EXTRA_BOUND, але «04.06.2023р.» і
    «о 13.40» речення не кінчають."""
    b = set(F._bounds(t))
    for m in EXTRA_BOUND.finditer(t):
        b.add(m.start() + m.group(0).index('.') + 1)
    return sorted(x for x in b if not re.search(r'(?:\d{4}\s?р|\d)\.$', t[:x].rstrip()))


def _start(text):
    bs = A.body_start(text)
    sec = _section(text, bs)
    if sec:
        tail = SECTION_TAIL.match(text, sec.end())
        return tail.end() if tail else sec.end()
    if bs:
        return bs
    m = KUPAP_START.search(text)
    return m.start() if m else 0


# «Як встановлено в судовому засіданні, ОСОБА_2, 19.12.2024…» — вступний
# зворот; без нього «судовому засіданні» вбивало б речення з самою подією.
OPEN_COURT = re.compile(r'^(?:як\s+)?(?:судом\s+)?(?:встановлено|встановив\s+суд)\s+(?:в|у)\s+судовому\s+'
                        r'засіданні\s*,?\s*(?:що\s*,?\s*)?', re.I)
# Процедура, яка лишається процедурою навіть з учасником і датою в реченні.
HARD_JUNK = re.compile(r'надійш|ЄРДР|Єдиного\s+реєстру|клопотан|обвинувальн\w*\s+акт', re.I)


def _is_junk(s):
    """Процедурне речення. Учасник із датою — уже опис («ОСОБА_3 20 серпня
    2023 року, діючи в умовах воєнного стану, вирішив…»), якщо тільки це не
    надходження справи чи реєстр."""
    if COURT_PROC.search(s):
        return True             # засідання, неявка, привід — процедура завжди
    if not LEAD_JUNK.search(s):
        return False
    if ACTOR.search(s) and HAS_DATE.search(s) and not HARD_JUNK.search(s):
        return False
    return True


def _drop_lead(t):
    """Відкидає процедурні речення й абзац про воєнний стан на початку."""
    for _ in range(8):
        b = _bounds(t)
        first = t[:b[0]] if b else t
        junk = _is_junk(first)
        if is_event_sentence(first) or not junk or not b:
            if junk and re.search(r'надійш', first):
                m = INNER_START.search(first, 20)
                if m:
                    t = t[m.start():]
            break
        t = t[b[0]:].lstrip()
    return t


def _event_anchor(t):
    """Перше речення з датою й часом — звідти починається опис, коли звичайні
    маркери привели не туди (позиція сторін, роз'яснення прав, шапка)."""
    starts = [0] + _bounds(t)
    for i, s in enumerate(starts):
        e = starts[i + 1] if i + 1 < len(starts) else len(t)
        if is_event_sentence(t[s:e]):
            return s
    return None


def _cut(t, cap):
    """Не довше за cap, і лише по межі речення. Якщо межі немає зовсім —
    по слову з трикрапкою: так видно, що текст неповний."""
    if len(t) <= cap:
        return t
    b = [x for x in _bounds(t) if x <= cap]
    return t[:b[-1]] if b else t[:cap].rsplit(' ', 1)[0] + '…'


def fabula(text):
    """Фабула з логічними межами, без стелі: (текст, чи знайдено кінець)."""
    # «\~», «\*» — залишки RTF, які rtf_to_text не прибрав
    body = re.sub(r'\s+', ' ', re.sub(r'\\[~*\-]', ' ', text[_start(text):])).strip()
    if SHORT_VERDICT.search(body[:400]):
        return '', False
    t = F.OPEN.sub('', body).strip()
    t = OPEN_COURT.sub('', t).strip()
    t = F._drop_preamble(t)
    t = _drop_lead(t)
    fab, found = _ends(t)
    # Фабула без дати або з одного звороту — маркери привели не туди. Тоді
    # беремо від першого речення з датою й часом у тексті після шапки.
    # Коротка постанова КУпАП з датою — нормальна, її не чіпаємо.
    if len(fab) < 120 or not event_date(fab):
        a = _event_anchor(body)
        if a is not None:
            fab2, found2 = _ends(body[a:])
            if len(fab2) >= len(fab) or not event_date(fab):
                return fab2, found2
        elif not event_date(fab):
            # Ні дати події, ні речення з датою й часом — це не фабула, а
            # процедура: постанова про привід, про об'єднання справ, абзац про
            # права сторін. Справжня фабула дату має майже завжди (138 зі 140
            # на вибірці 23.09). Чесне «опису немає» (клас D) краще за уривок.
            return '', False
    # Кожне речення — процедура (клопотання про речовий доказ, стара постанова
    # у справі): опису немає, хоч дата й трапилась.
    st = [0] + _bounds(fab)
    sents = [fab[a:b] for a, b in zip(st, st[1:] + [len(fab)]) if fab[a:b].strip()]
    if sents and all(_is_junk(s) for s in sents) and not any(is_event_sentence(s) for s in sents):
        return '', False
    return fab, found


# «будучи притягнутим … за дії, передбачені ч. 1 ст. 130 КУпАП, керував …»:
# тут «передбачені» — про попереднє стягнення, а фабула йде далі.
# Так само «від невстановленої особи, матеріали щодо якої виділено, за
# ознаками правопорушення, передбаченого ч. 1 ст. 307 КК, придбала …» —
# це стаття іншої особи посеред опису.
PRIOR = re.compile(r'(?:за\s+(?:дії|правопорушення)\s*,?|притягнут\w+.{0,80}|за\s+ознаками\s+.{0,70})\s*$', re.I)


def _stop(t):
    for m in F.STOP.finditer(t):
        g = m.group(0).lower()
        if g.startswith('передбачен') and PRIOR.search(t[max(0, m.start() - 120):m.start()]):
            continue
        # «знайшла, тим самим незаконно придбала …. В подальшому, 14.02.2024
        # о 13.30 … було зупинено» — у наркотичних справах «тим самим
        # придбав» стоїть посеред опису, коли далі ще є епізод із датою й часом
        if g.startswith('тим') and _event_anchor(t[m.end():m.end() + 1500]) is not None:
            continue
        return m.start()
    return None


def _ends(t):
    e = END.search(t, MIN_BEFORE_END)
    ends = [x for x in (_stop(t), e.start() if e else None) if x is not None]
    m2 = F.TAIL.search(t)
    if m2 and m2.start() >= 80:
        ends.append(m2.start())
    found = bool(ends)
    if ends:
        t = t[:min(ends)]
        b = _bounds(t)
        if b and len(t) - b[-1] < STUB:
            t = t[:b[-1]]
    t = t.rstrip(' ,.;:—-')
    # «…крововилив в кон'юнктиві лівого ока, які [згідно висновку]» — маркер
    # відрізав підрядне речення, від нього лишилося сполучне слово
    t = re.sub(r'[,\s]+(?:які|який|яка|яке|що|та|і|й|а|де)$', '', t)
    # «…мобільний телефон «Самсунг», вартість якого [згідно висновку]» —
    # від підрядного лишився початок без присудка
    t = re.sub(r',[^,]{0,40}\b(?:якого|якої|яких|якому|якій)$', '', t)
    # «…без марок акцизного податку, у зв'язку з чим його дії» — від
    # кваліфікації лишився зв'язковий зворот без присудка
    t = re.sub(r'[,\s]+(?:у\s+зв.?язку\s+з\s+чим|тим\s+самим|внаслідок\s+чого|чим)\b[^.,]{0,40}$', '', t)
    # «…де останнього було затримано, згідно ст. 298-2» — від посилання на
    # статтю лишився самий номер
    t = re.sub(r'[,\s]+(?:згідно|відповідно\s+до|на\s+підставі|в\s+порядку)\s+(?:з\s+)?(?:ч\.?\s*\d+\s*)?'
               r'ст\.?\s*[\d\-]+$', '', t)
    return t, found


# Дата поруч із цими словами — дата указу, закону, реєстрації чи
# надходження справи, а не події.
# Вікно коротке (DATE_CTX): «протоколу серії ГП №532688 від 17 лютого 2024
# року, ОСОБА_1 17.02.2024 о 01:00» — номер протоколу стоїть перед датою
# протоколу, а не перед датою події.
DATE_NOT_EVENT = re.compile(r'Указ|Закон|воєнн|ЄРДР|реєстр|надійш|засідан|призначен\w*\s+на|від\s*$', re.I)
DATE_CTX = 30


def event_date(fab):
    """Перша дата в описі, що не є датою документа, — дата події. ISO або ''."""
    cands = []
    for m in DATE_NUM.finditer(fab):
        d, mo, y = int(m.group(1)), int(m.group(2)), int(m.group(3))
        if 1 <= d <= 31 and 1 <= mo <= 12:
            cands.append((m.start(), f'{y:04d}-{mo:02d}-{d:02d}'))
    for m in DATE_TXT.finditer(fab):
        cands.append((m.start(), f'{int(m.group(3)):04d}-{MONTHS[m.group(2).lower()]:02d}-{int(m.group(1)):02d}'))
    for pos, iso in sorted(cands):
        if DATE_NOT_EVENT.search(fab[max(0, pos - DATE_CTX):pos]):
            continue
        # «з 05 години 30 хвилин 24 лютого 2022 року», «продовжено з 05
        # листопада 2025» — дати указів про воєнний стан, а не подія, навіть
        # коли речення далі переходить до учасника. Дата належить указу, якщо
        # між згадкою указу й датою ще не було учасника.
        before = fab[max(0, pos - 300):pos]
        # лише в межах того самого речення: указ у попередньому реченні дату
        # події вже не зачіпає
        sb = list(re.finditer(r'\.\s+(?=[А-ЯІЇЄҐ])', before))
        if sb:
            before = before[sb[-1].end():]
        mm = list(MARTIAL.finditer(before))
        if iso == '2022-02-24' or (mm and not ACTOR.search(before[mm[-1].end():])):
            if mm or MARTIAL.search(fab[pos:pos + 150]):
                continue
        return iso
    return ''


def event_time(fab):
    for m in TIME.finditer(fab):
        hh, mm = int(m.group(1)), int(m.group(2) or 0)
        if 0 <= hh <= 23 and 0 <= mm <= 59:
            return f'{hh:02d}:{mm:02d}'
    return ''


def rozbir(text, cat):
    """Усе, що прохід бере з одного тексту рішення."""
    full, found = fabula(text)
    res = A.extract(text)
    sent = ''
    if res.get('pos') is not None:
        p = res['pos']
        sent = re.sub(r'\s+', ' ', text[A.sentence_start(text, p):A.sentence_end(text, p)]).strip()
    kd = kodeks(cat)
    return dict(
        fab=_cut(full, CAP[kd]), fab_len=len(full), end_found=found, kodeks=kd,
        date=event_date(full), time=event_time(full) or (res.get('time') or ''),
        addr_sentence=sent, street=res['street'] or '', house=res['house'] or '',
        level=res['level'],
        # клас — на логічній фабулі до стелі: так межа B/C не залежить від обрізу
        klass=PD.addr_class(full, res['street']))
