# У постановах КУпАП без «ВСТАНОВИВ» опис іде від «згідно (з) протоколу».
KUPAP_START = re.compile(r'згідно\s+(?:з\s+|із\s+)?протокол\w*', re.I)
# Сучасні вироки мають розділи: «І. Історія провадження» (процедура) і далі
# «Встановлені судом обставини» чи «Формулювання обвинувачення». Коли такий
