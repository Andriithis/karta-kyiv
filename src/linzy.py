# -*- coding: utf-8 -*-
"""Дані лінз «Порушник» і «Ціль» (36.41; мінімальна версія 28.10 —
doslidzhennya/linzy/MVP-28-10.md) — з фабули, яка вже є: ознаки порушника
(вирази першого проходу центрального чату, README розд. 3), стать за формою
слів і ціль (src/tsil.py). Поля особи зі вступу рішення — наступним кроком.

Число ознаки — те, що суд **написав**, а не все, що було: «повторно» в ДТП,
порядку й торгівлі майже не пишуть, тож це мінімум.
"""
import re
import tsil as TS

# Біти ознак у даних карти; групи — як на сторінці «Заходи» (Андрій 27.10).
# «Припису» немає (36.41): ст.173-2 суд знеособлює («АДРЕСА_1»), тож на карту
# доходило 3 події з 250. Усе — з фабули й статті, без нового проходу.
POVTORNO_RIK = re.compile(r'повторн\w*\s+протягом\s+(?:одного\s+)?року', re.I)
POVTORNO = re.compile(r'(?<![А-Яа-яІіЇїЄєҐґ])повторн', re.I)
# README розд. 3. Почерк суду про судимість різний (0,7–15,5% за районами), але
# для пошуку особи це не заважає — заважає лише порівнянню районів
SUDYMYI = re.compile(r'раніше\s+(?:неодноразово\s+)?судим|непогашен\w*\s+(?:у встановленому законом порядку\s+)?судим'
                     r'|не\s?знят\w*\s+(?:і|та)\s+не\s?погашен', re.I)
ZVILNENYI = re.compile(r'звільн\w*\s+з\s+місць\s+позбавлення|звільнившись\s+з\s+місць', re.I)
ISPYTOVYI = re.compile(r'іспитов\w*\s+строк', re.I)
# Неповнолітній — саме правопорушник. «Неповнолітній ОСОБА_1» на початку
# речення, після часу чи адреси — так; «в бік / щодо / завдав неповнолітньому»,
# «неповнолітній потерпілій», «продала неповнолітній ОСОБА_2» — ні: перед
# словом стоїть інше слово, і це потерпілий. Тому дивимося, що перед збігом.
NEPOVN_OS = re.compile(r'неповнолітн(?:ій|я)\s+(?:(?:обвинувачен|правопорушни|підозрюван)\w*\s+)?ОСОБА_\d+', re.I)
NEPOVN_INSHE = re.compile(r'будучи\s+неповнолітн\w*|(?<![А-Яа-яІіЇїЄєҐґ])(?:є|був|була)\s+неповнолітн(?:ім|ьою)(?![А-Яа-яІіЇїЄєҐґ])'
                          r'|неповнолітн(?:ій|я)\s+(?:обвинувачен|правопорушни|підозрюван)\w*', re.I)
NEPOVN_PERED = {'виявлений', 'виявлена', 'встановлено', 'що'}
# ст.156 КУпАП ч.2 — продаж особам до 18 років; частини статті в даних немає,
# тож лише з фабули
PRODAZH_DITIAM = re.compile(r'ч(?:астин\w*)?\.?\s*2\s*ст(?:ат\w*)?\.?\s*156|неповнолітн|не\s+досяг\w*\s+(?:18|вісімнадцят)', re.I)
ST_156, ST_173_4, ST_192 = {'41128', '5987'}, {'12581'}, {'41333', '6143'}
DITY, DOROSLI = 'Діти', 'Дорослі'
OZNAKY = [(32, 'nepovnolitnii', 'Неповнолітній правопорушник', DITY),
          (64, 'buling', 'Булінг', DITY),
          (128, 'prodazh_ditiam', 'Продаж алкоголю чи тютюну дітям', DITY),
          (1, 'povtorno_kk', 'Повторно у кримінальній справі', DOROSLI),
          (4, 'povtorno_rik', 'Повторно протягом року', DOROSLI),
          (2, 'sudymyi', 'Раніше судимий', DOROSLI),
          (8, 'ispytovyi', 'Іспитовий строк', DOROSLI),
          (16, 'zvilnenyi', 'Звільнений з місць позбавлення волі', DOROSLI),
          (256, 'zbroia', 'Власник зброї: порушив зберігання', DOROSLI)]
# вираз, біля якого показувати вікно у вибірці для перевірки очима
VYRAZ = {'sudymyi': SUDYMYI, 'zvilnenyi': ZVILNENYI, 'ispytovyi': ISPYTOVYI, 'prodazh_ditiam': PRODAZH_DITIAM,
         'povtorno_rik': POVTORNO_RIK, 'povtorno_kk': POVTORNO}


def ispytovyi(t):
    """іспитовий строк за попереднім вироком; «звільнити … якщо протягом …
    іспитового строку» — це резолютивна частина нинішнього вироку, не особа"""
    for m in ISPYTOVYI.finditer(t):
        if not re.search(r'звільнити', t[max(0, m.start() - 160):m.start()], re.I):
            return m
    return None


def nepovnolitnii(t):
    """збіг «неповнолітній — правопорушник» або None"""
    for m in NEPOVN_OS.finditer(t):
        pered = t[max(0, m.start() - 40):m.start()].rstrip()
        slovo = (pered.split() or [''])[-1].lower()
        if not pered or not pered[-1].isalpha() or slovo in NEPOVN_PERED:
            return m
    return NEPOVN_INSHE.search(t)

# Стать — за формою дієслова дії особи (вчинив / вчинила). Обидві форми чи
# жодної — невідомо: у фабулі буває й потерпіла, і поліцейська.
STAT_Ж = re.compile(r'(?<![а-яіїєґ])(?:вчинила|скоїла|керувала|перебувала|викрала|здійснила|заволоділа|придбала|'
                    r'зберігала|розпивала|торгувала|виражалась|виражалася|порушила|ухилилась|ухилилася)(?![а-яіїєґ])',
                    re.I)
STAT_Ч = re.compile(r'(?<![а-яіїєґ])(?:вчинив|скоїв|керував|перебував|викрав|здійснив|заволодів|придбав|'
                    r'зберігав|розпивав|торгував|виражався|порушив|ухилився)(?![а-яіїєґ])', re.I)


def oznaky(fab, kd, cat=''):
    """біти ознак порушника з фабули й статті; kd — кодекс статті ('КК' чи
    'КУпАП'), cat — код статті (labels.CODE)"""
    t = fab or ''
    b = 0
    rik = bool(POVTORNO_RIK.search(t))
    if rik: b |= 4
    # «повторно» у кримінальній справі — не «протягом року» (README, розд. 3)
    if kd == 'КК' and POVTORNO.search(POVTORNO_RIK.sub(' ', t)): b |= 1
    if SUDYMYI.search(t): b |= 2
    if ispytovyi(t): b |= 8
    if ZVILNENYI.search(t): b |= 16
    # у ст.156 неповнолітній — покупець, а не правопорушник
    if cat not in ST_156 and nepovnolitnii(t): b |= 32
    if cat in ST_173_4: b |= 64
    if cat in ST_156 and PRODAZH_DITIAM.search(t): b |= 128
    if cat in ST_192: b |= 256
    return b


def stat(fab):
    t = fab or ''
    zh, ch = bool(STAT_Ж.search(t)), bool(STAT_Ч.search(t))
    return 'ж' if zh and not ch else 'ч' if ch and not zh else ''


# Ціль — підпис пункту шторки за видом (макет трикутника, п. 7). «merezha» —
# не окремий пункт, а частина «у кого: магазин».
TSIL_NAZVA = {'berut': 'Беруть', 'u_koho': 'У кого', 'zitknennia': 'Зіткнення з', 'na_koho': 'На кого',
              'rechovyna': 'Речовина', 'sposib': 'Як', 'shcho_prodaiut': 'Продають'}


def tsil_kody(theme, sim, fab):
    """['поле=значення', …] для шторки «Ціль»"""
    return [f'{k}={v}' for k, v in TS.tsil(theme, sim, fab).items() if k in TSIL_NAZVA]
